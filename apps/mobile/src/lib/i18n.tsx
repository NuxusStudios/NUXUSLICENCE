export type Lang = 'en' | 'fr';

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey) => string;
  /** Pick the right side of a { en, fr } pair from the API. */
  pick: (v: { en: string; fr: string }) => string;
}

const Ctx = createContext<I18n | null>(null);

function deviceLang(): Lang {
  try {
    return getLocales()[0]?.languageCode === 'fr' ? 'fr' : 'en';
  } catch {
    return 'en';
  }
}

const LANG_KEY = 'civicpass.lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(deviceLang);

  // An explicit choice overrides the device language and survives restarts.
  useEffect(() => {
    void secureStorage.get(LANG_KEY).then((saved) => {
      if (saved === 'en' || saved === 'fr') setLangState(saved);
    });
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    void secureStorage.set(LANG_KEY, l);
  }, []);

  const t = useCallback((key: TKey) => (lang === 'fr' ? fr[key] ?? en[key] : en[key]), [lang]);
  const pick = useCallback((v: { en: string; fr: string }) => v[lang], [lang]);
  const value = useMemo(() => ({ lang, setLang, t, pick }), [lang, setLang, t, pick]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
