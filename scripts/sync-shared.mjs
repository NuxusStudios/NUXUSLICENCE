// Copies packages/shared into each app. The apps build independently (tsc for
// the API, Metro for the mobile app), so the shared core is vendored rather
// than linked. apps/api/test/shared.test.ts fails if a copy drifts.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/shared');
const targets = ['apps/api/src/shared', 'apps/mobile/src/lib/shared'];
const banner = '// GENERATED by scripts/sync-shared.mjs from packages/shared. Do not edit.\n';

for (const file of readdirSync(src).filter((f) => f.endsWith('.ts'))) {
  const body = banner + readFileSync(join(src, file), 'utf8');
  for (const t of targets) {
    mkdirSync(join(root, t), { recursive: true });
    writeFileSync(join(root, t, file), body);
  }
  console.log(`synced ${file} -> ${targets.join(', ')}`);
}
